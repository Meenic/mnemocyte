// Writes src/db/libsql/bundled.ts from migrations/libsql/, so the libSQL
// store's `migrate()` ships the SQL without reading files at runtime, as
// scripts/bundle-migrations.ts does for Postgres. The template is migration
// 0000 and always holds the final schema: a fresh install renders it and
// records every migration. Later migrations are the files named
// NNNN_name.sql from 0001, without a gap. With --stdout it prints the module
// instead and writes nothing, which the drift test compares with the file.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const migrationsDir = resolve(root, "migrations/libsql");
const outFile = resolve(root, "src/db/libsql/bundled.ts");

interface Migration {
	version: number;
	name: string;
	sql: string;
}

async function readSql(name: string): Promise<string> {
	const text = await readFile(resolve(migrationsDir, name), "utf8");
	return text.replaceAll("\r\n", "\n");
}

const files = (await readdir(migrationsDir))
	.filter((name) => /^\d{4}_[a-z0-9_]+\.sql$/.test(name))
	.sort();
const migrations: Migration[] = [];
for (const [index, file] of files.entries()) {
	const version = Number(file.slice(0, 4));
	if (version !== index + 1) {
		throw new Error(
			`Expected migration ${String(index + 1).padStart(4, "0")}, found ${file}.`,
		);
	}
	migrations.push({
		version,
		name: file.slice(0, -".sql".length),
		sql: await readSql(file),
	});
}
const template = await readSql("0000_initial.sql.template");

function templateLiteral(text: string): string {
	const escaped = text
		.replaceAll("\\", "\\\\")
		.replaceAll("`", "\\`")
		.replaceAll("${", "\\${");
	return `\`${escaped}\``;
}

const entries = migrations
	.map(
		(migration) =>
			`\t{\n\t\tversion: ${migration.version},\n\t\tname: ${JSON.stringify(migration.name)},\n\t\tsql: ${templateLiteral(migration.sql)},\n\t},\n`,
	)
	.join("");

// Biome formats an empty array as `[]`, so only a filled one gets a newline.
const list = entries === "" ? "" : `\n${entries}`;

const module = `// Generated by scripts/bundle-libsql-migrations.ts from migrations/libsql/.
// Do not edit; run \`pnpm migration:bundle\` after changing a migration or the
// template.

export interface LibsqlBundledMigration {
	readonly version: number;
	readonly name: string;
	readonly sql: string;
}

/** The name migration 0000, the rendered template, is recorded under. */
export const LIBSQL_INITIAL_MIGRATION_NAME = "0000_initial";

/** The numbered migrations after 0000 in \`migrations/libsql/\`, in order. */
export const LIBSQL_MIGRATIONS: readonly LibsqlBundledMigration[] = [${list}];

/** \`migrations/libsql/0000_initial.sql.template\`: the final schema. */
export const LIBSQL_SCHEMA_TEMPLATE: string = ${templateLiteral(template)};
`;

if (process.argv.includes("--stdout")) {
	process.stdout.write(module);
} else {
	await writeFile(outFile, module);
}
